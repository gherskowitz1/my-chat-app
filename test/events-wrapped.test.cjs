// Game Night events (recurring series, sign-in sheets, check-ins) and the
// Wrapped recap — the SQL-heavy features, against real Postgres.
const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('path');
const { startApp, signup, SRC } = require('./helpers.cjs');

const DAY = 24 * 60 * 60 * 1000;
const fakeIo = () => { const sent = []; return { sent, emit: (e, p) => sent.push({ e, p }) }; };

test('weekly series: dates stocked ahead, each with its own sign-in sheet', async () => {
  const app = await startApp();
  try {
    const alice = await signup(app, 'alice');
    const bob = await signup(app, 'bob');
    const firstDate = new Date(Date.now() + 2 * DAY);
    const created = await app.post('/events', {
      title: 'Friday Game Night', startsAt: firstDate.toISOString(), recurrence: 'weekly', timeZone: 'America/New_York',
    }, alice.token);
    assert.equal(created.status, 201, JSON.stringify(created.data));
    assert.equal(created.data.recurrence, 'weekly');

    const list = (await app.get('/events', bob.token)).data;
    assert.ok(list.length >= 2, `expected next week's date too, got ${list.length}`);
    const [first, second] = list;
    assert.equal(new Date(second.starts_at) - new Date(first.starts_at), 7 * DAY, 'one week apart (no DST between here)');
    assert.deepEqual(first.rsvps.map((r) => r.username), ['alice'], 'creator going to the first date');
    assert.equal(second.rsvps.length, 0, 'next week starts blank');

    // RSVP to week 2 doesn't touch week 1.
    assert.equal((await app.post(`/events/${second.id}/rsvp`, { status: 'no' }, bob.token)).status, 200);
    const after = (await app.get('/events', bob.token)).data;
    assert.equal(after[0].rsvps.find((r) => r.username === 'bob'), undefined);
    assert.equal(after[1].rsvps.find((r) => r.username === 'bob').status, 'no');
    assert.ok(app.emitted.some((e) => e.event === 'events:changed'));
  } finally { await app.close(); }
});

test('cancel one date vs end the series; only creator/admin may cancel', async () => {
  const app = await startApp();
  try {
    const alice = await signup(app, 'alice');
    const bob = await signup(app, 'bob');
    await app.post('/events', {
      title: 'Weekly', startsAt: new Date(Date.now() + DAY).toISOString(), recurrence: 'weekly', timeZone: 'UTC',
    }, alice.token);
    let list = (await app.get('/events', alice.token)).data;
    assert.equal((await app.del(`/events/${list[0].id}?scope=one`, bob.token)).status, 403, "bob didn't schedule it");

    assert.equal((await app.del(`/events/${list[0].id}?scope=one`, alice.token)).status, 200);
    list = (await app.get('/events', alice.token)).data;
    assert.ok(list.length >= 1, 'the rest of the series remains');

    // The cancelled date must not be regenerated by the job.
    const { runOnce } = require(path.join(SRC, 'jobs', 'eventReminders.js'));
    await runOnce(fakeIo());
    const { rows } = await app.pool.query('SELECT COUNT(*)::int AS n FROM events WHERE cancelled_at IS NOT NULL');
    assert.equal(rows[0].n, 1);
    assert.equal((await app.get('/events', alice.token)).data.length, list.length, 'skipped week stays skipped');

    assert.equal((await app.del(`/events/${list[0].id}?scope=series`, alice.token)).status, 200);
    assert.equal((await app.get('/events', alice.token)).data.length, 0, 'series ended');
    await runOnce(fakeIo());
    assert.equal((await app.get('/events', alice.token)).data.length, 0, 'ended series not restocked');
  } finally { await app.close(); }
});

test('week-before check-in goes once, only to people who have not answered', async () => {
  const app = await startApp();
  try {
    const alice = await signup(app, 'alice');
    await signup(app, 'bob');
    await signup(app, 'carol');
    const created = await app.post('/events', { title: 'Big game', startsAt: new Date(Date.now() + 6 * DAY).toISOString() }, alice.token);
    // Pretend it was scheduled two weeks ago, so it qualifies for a check-in.
    await app.pool.query("UPDATE events SET created_at = NOW() - INTERVAL '14 days' WHERE id = $1", [created.data.id]);
    const { rows: [carol] } = await app.pool.query("SELECT id FROM users WHERE username = 'carol'");
    await app.pool.query("INSERT INTO event_rsvps (event_id, user_id, status) VALUES ($1, $2, 'no')", [created.data.id, carol.id]);

    const { runOnce } = require(path.join(SRC, 'jobs', 'eventReminders.js'));
    await runOnce(fakeIo());
    const { rows } = await app.pool.query('SELECT checkin_sent_at FROM events WHERE id = $1', [created.data.id]);
    assert.ok(rows[0].checkin_sent_at, 'check-in marked sent');
    await runOnce(fakeIo());
    const { rows: again } = await app.pool.query('SELECT checkin_sent_at FROM events WHERE id = $1', [created.data.id]);
    assert.equal(again[0].checkin_sent_at.getTime(), rows[0].checkin_sent_at.getTime(), 'not sent twice');
  } finally { await app.close(); }
});

