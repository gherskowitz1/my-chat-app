test('event input validation', async () => {
  const app = await startApp();
  try {
    const alice = await signup(app, 'alice');
    const soon = new Date(Date.now() + DAY).toISOString();
    assert.equal((await app.post('/events', { title: '', startsAt: soon }, alice.token)).status, 400);
    assert.equal((await app.post('/events', { title: 'x', startsAt: '2020-01-01T00:00:00Z' }, alice.token)).status, 400);
    assert.equal((await app.post('/events', { title: 'x', startsAt: soon, recurrence: 'daily', timeZone: 'UTC' }, alice.token)).status, 400);
    assert.equal((await app.post('/events', { title: 'x', startsAt: soon, recurrence: 'weekly', timeZone: 'Mars/Olympus' }, alice.token)).status, 400);
    assert.equal((await app.post('/events', { title: 'x', startsAt: soon, voiceChannelId: '00000000-0000-0000-0000-000000000001' }, alice.token)).status, 400, 'a text channel is not a voice channel');
    assert.equal((await app.post('/events', { title: 'x', startsAt: soon, voiceChannelId: '00000000-0000-0000-0000-000000000003' }, alice.token)).status, 201);
  } finally { await app.close(); }
});

test('Wrapped: stats computed for the year, in the viewer’s time zone', async () => {
  const app = await startApp();
  try {
    const alice = await signup(app, 'alice');
    await signup(app, 'bob');
    // (The schema seeds a PatchBot user too, so look these two up by name.)
    const { rows: users } = await app.pool.query("SELECT id, username FROM users WHERE username IN ('alice', 'bob') ORDER BY username");
    const [a, b] = users;
    const year = new Date().getUTCFullYear();
    await app.pool.query("UPDATE users SET time_zone = 'Asia/Tokyo' WHERE id = $1", [a.id]);
    const general = '00000000-0000-0000-0000-000000000001';
    const at = (iso) => new Date(iso).toISOString();
    // Two of alice's messages at 23:30 Tokyo time; one of bob's.
    const insertMsg = (userId, content, when, replyTo = null) => app.pool.query(
      'INSERT INTO messages (channel_id, user_id, content, created_at, reply_to_id) VALUES ($1, $2, $3, $4, $5) RETURNING id',
      [general, userId, content, when, replyTo]
    );
    const { rows: [bobMsg] } = await insertMsg(b.id, 'hi alice', at(`${year}-03-14T10:00:00Z`));
    await insertMsg(a.id, 'lol 😂😂', at(`${year}-03-14T14:30:00Z`), bobMsg.id);
    await insertMsg(a.id, 'gg 😂', at(`${year}-03-14T14:40:00Z`));
    await app.pool.query('INSERT INTO message_reactions (message_id, user_id, emoji) VALUES ($1, $2, $3)', [bobMsg.id, a.id, '🔥']);
    await app.pool.query(
      "INSERT INTO voice_sessions (user_id, channel_id, started_at, last_seen_at, ended_at) VALUES ($1, '00000000-0000-0000-0000-000000000003', NOW() - INTERVAL '2 hours', NOW(), NOW() - INTERVAL '30 minutes')",
      [a.id]
    );

    const res = await app.get(`/wrapped?year=${year}`, alice.token);
    assert.equal(res.status, 200, JSON.stringify(res.data));
    const w = res.data;
    assert.equal(w.timeZone, 'Asia/Tokyo');
    assert.equal(w.messagesSent, 2);
    assert.equal(w.serverMessages, 3);
    assert.equal(w.rank, 1);
    assert.equal(w.topChannels[0].name, 'general');
    assert.equal(w.replyBuddy.username, 'bob');
    assert.equal(w.topEmoji[0].emoji, '😂');
    assert.equal(w.topEmoji[0].count, 3);
    assert.equal(w.reactionsGiven, 1);
    assert.equal(w.busiestHour, 23, '14:30 UTC is 23:30 in Tokyo');
    assert.equal(w.voiceHours, 1.5);
    assert.equal(w.topVoiceChannel, 'General Voice');
    assert.equal((await app.get('/wrapped?year=1999', alice.token)).status, 400);
  } finally { await app.close(); }
});
